import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
const R='/Users/son7/Projects/tseng-law-all-locales-20261025';
const B='/Users/son7/tseng-all-language-columns-20261025/batch05';
const require=createRequire(path.join(R,'package.json'));
const matter=require('gray-matter');
const hash=b=>createHash('sha256').update(b).digest('hex');
const urls=s=>new Set([...s.matchAll(/\]\((https?:\/\/[^\s)]+)\)/g)].map(m=>m[1]));
const slugs=['taiwan-arc-first-application','taiwan-visa-residence-work-study-family','taiwan-arc-renewal-changes-reentry'];
const rows=[];
for(const [i,slug] of slugs.entries()){
 const file=path.join(B,`src/content/columns-lt/${704+i}-${slug}.md`);
 const raw=fs.readFileSync(file),{data,content}=matter(raw.toString());
 const en=matter(fs.readFileSync(path.join(R,`src/content/columns-en/${704+i}-${slug}.md`),'utf8'));
 const errors=[];const check=(ok,label)=>{if(!ok)errors.push(label)};
 check(data.published==='2026-10-26'&&data.lastmod==='2026-10-26','dates');
 check(data.date_display==='2026 m. spalio 26 d.','localized date');
 check(JSON.stringify(data.audience)==='["lt"]','audience');
 check(data.author==='legal-ai-assistant','internal author');
 check(data.topic==='visa','topic');
 check(data.categories?.includes('Teisinė informacija apie Taivaną'),'category');
 for(const key of ['title','seoTitle','summary','featured_image_alt','read_time'])check(typeof data[key]==='string'&&data[key].trim().length>0,key);
 check(data.featured_image===en.data.featured_image&&fs.existsSync(path.join(R,'public',data.featured_image)),'original image exists');
 check(data.featured_image_caption==='Išgalvota scena','fiction caption');
 check(data.faq?.length===3&&data.faq.every(x=>x.q?.trim()&&x.a?.trim()),'FAQ3');
 check(!/(\*\*|__|<\/?(?:strong|b)\b)/i.test(content),'bold');
 check(!/^#\s/m.test(content),'body H1');
 check(!/legal-ai-assistant|Wei Tseng/.test(content),'public byline');
 const [prose,footer]=content.split('## Oficialūs šaltiniai');
 check(!!footer,'source footer');
 const all=urls(content),inline=urls(prose),end=urls(footer??'');
 const missingEn=[...urls(en.content)].filter(u=>!all.has(u));
 const missingFooter=[...inline].filter(u=>!end.has(u));
 check(!missingEn.length,'EN source URL missing');check(!missingFooter.length,'inline source absent from footer');
 const internal=[...content.matchAll(/\]\((\/(?:lt|en)\/columns\/[^\s)]+)\)/g)].map(m=>m[1]);
 const internalChecks=internal.map(url=>{const[,locale,,target]=url.split('/');const dir=locale==='lt'?path.join(B,'src/content/columns-lt'):path.join(R,'src/content/columns-en');return{url,exists:fs.readdirSync(dir).some(n=>n.replace(/^\d+-/,'').replace(/\.md$/,'')===target)}});
 check(internalChecks.every(x=>x.exists),'broken internal target');
 check(content.includes('2026 m. spalio 24–25 d.'),'source date unchanged');
 rows.push({file,sha256:hash(raw),bytes:raw.length,proseWords:prose.replace(/\]\([^)]*\)/g,']').split(/\s+/).filter(Boolean).length,officialURLs:all.size,baselineEnURLs:urls(en.content).size,missingEn,missingFooter,internalChecks,errors});
}
const inputs=JSON.parse(fs.readFileSync(path.join(B,'checks/lt-inputs.json'),'utf8'));
const changedInputs=inputs.files.filter(x=>hash(fs.readFileSync(x.path))!==x.sha256).map(x=>x.path);
const report={at:new Date().toISOString(),node:process.version,rows,changedInputs,errors:rows.reduce((n,r)=>n+r.errors.length,0)+changedInputs.length};
fs.writeFileSync(path.join(B,'checks/lt-structure-after-options.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
if(report.errors)process.exitCode=1;
