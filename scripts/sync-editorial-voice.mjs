import { readFile, writeFile } from 'node:fs/promises';

// The checked-in document travels with worktrees and deployment builds.
const policy = await readFile(new URL('../docs/columns/EDITORIAL-VOICE.md', import.meta.url), 'utf8');
const output = `// Generated by scripts/sync-editorial-voice.mjs; edit docs/columns/EDITORIAL-VOICE.md.\nexport const EDITORIAL_VOICE = ${JSON.stringify(policy.split('\n'), null, 2)}.join('\\n');\n`;
await writeFile(new URL('../src/lib/editorial-voice.generated.ts', import.meta.url), output);
